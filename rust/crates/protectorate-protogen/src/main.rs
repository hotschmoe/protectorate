//! Writes prost message types for one protobuf package from a descriptor set.
//! Usage: protectorate-protogen DESCRIPTOR_SET PACKAGE OUTPUT
use prost_reflect::{
    Cardinality, DescriptorPool, EnumDescriptor, FieldDescriptor, Kind, MessageDescriptor,
};
use std::fmt::Write;

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let [descriptor, package, output] = args.as_slice() else {
        eprintln!("usage: protectorate-protogen DESCRIPTOR_SET PACKAGE OUTPUT");
        std::process::exit(2);
    };
    let bytes = std::fs::read(descriptor).unwrap_or_else(|e| fail(&format!("{descriptor}: {e}")));
    let pool = DescriptorPool::decode(bytes.as_slice())
        .unwrap_or_else(|e| fail(&format!("{descriptor}: {e}")));
    let code = render(&pool, package);
    std::fs::write(output, code).unwrap_or_else(|e| fail(&format!("{output}: {e}")));
}

fn fail(message: &str) -> ! {
    eprintln!("protectorate-protogen: {message}");
    std::process::exit(1)
}

fn render(pool: &DescriptorPool, package: &str) -> String {
    let mut out = String::from(
        "// @generated by protectorate-protogen from the embedded descriptor set. Do not edit.\n",
    );
    let mut messages: Vec<_> = pool
        .all_messages()
        .filter(|m| m.package_name() == package && !m.is_map_entry())
        .collect();
    messages.sort_by(|a, b| a.full_name().cmp(b.full_name()));
    let mut enums: Vec<_> = pool
        .all_enums()
        .filter(|e| e.package_name() == package)
        .collect();
    enums.sort_by(|a, b| a.full_name().cmp(b.full_name()));
    for message in &messages {
        if message.parent_message().is_some() {
            fail(&format!(
                "nested message {} is not supported",
                message.full_name()
            ));
        }
        render_message(&mut out, package, message);
    }
    for e in &enums {
        if e.parent_message().is_some() {
            fail(&format!("nested enum {} is not supported", e.full_name()));
        }
        render_enum(&mut out, e);
    }
    let mut services: Vec<_> = pool
        .services()
        .filter(|s| s.package_name() == package)
        .collect();
    services.sort_by(|a, b| a.full_name().cmp(b.full_name()));
    for service in &services {
        let _ = writeln!(out, "pub mod {} {{", snake(service.name()));
        for method in service.methods() {
            let _ = writeln!(
                out,
                "    pub const {}: crate::Rpc<{}, {}> = crate::Rpc::new(\"/{}/{}\");",
                screaming_to_snake(method.name()).to_uppercase(),
                message_path(package, &method.input(), "super::"),
                message_path(package, &method.output(), "super::"),
                service.full_name(),
                method.name()
            );
        }
        out.push_str("}\n");
    }
    out
}

fn render_message(out: &mut String, package: &str, message: &MessageDescriptor) {
    let name = message.name();
    out.push_str("#[derive(Clone, PartialEq, ::prost::Message)]\n");
    let _ = writeln!(out, "pub struct {name} {{");
    let mut oneofs = Vec::new();
    for field in message.fields() {
        match field.containing_oneof() {
            Some(oneof) if !oneof.is_synthetic() => {
                if !oneofs
                    .iter()
                    .any(|o: &prost_reflect::OneofDescriptor| o.name() == oneof.name())
                {
                    let tags: Vec<String> =
                        oneof.fields().map(|f| f.number().to_string()).collect();
                    let _ = writeln!(
                        out,
                        "    #[prost(oneof = \"{}::{}\", tags = \"{}\")]\n    pub {}: ::core::option::Option<{}::{}>,",
                        snake(name),
                        camel(oneof.name()),
                        tags.join(", "),
                        ident(oneof.name()),
                        snake(name),
                        camel(oneof.name()),
                    );
                    oneofs.push(oneof);
                }
            }
            _ => {
                let (attr, ty) = field_type(package, &field);
                let _ = writeln!(
                    out,
                    "    #[prost({attr}, tag = \"{}\")]\n    pub {}: {ty},",
                    field.number(),
                    ident(field.name())
                );
            }
        }
    }
    out.push_str("}\n");
    let _ = writeln!(
        out,
        "impl ::prost_reflect::ReflectMessage for {name} {{\n    fn descriptor(&self) -> ::prost_reflect::MessageDescriptor {{\n        crate::message(\"{}\")\n    }}\n}}",
        message.full_name()
    );
    if oneofs.is_empty() {
        return;
    }
    let _ = writeln!(out, "pub mod {} {{", snake(name));
    for oneof in oneofs {
        out.push_str("    #[derive(Clone, PartialEq, ::prost::Oneof)]\n");
        let _ = writeln!(out, "    pub enum {} {{", camel(oneof.name()));
        for field in oneof.fields() {
            let (attr, ty) = scalar_or_message(package, &field, "super::");
            let _ = writeln!(
                out,
                "        #[prost({attr}, tag = \"{}\")]\n        {}({ty}),",
                field.number(),
                camel(field.name())
            );
        }
        out.push_str("    }\n");
    }
    out.push_str("}\n");
}

fn field_type(package: &str, field: &FieldDescriptor) -> (String, String) {
    if field.is_map() {
        let Kind::Message(entry) = field.kind() else {
            unreachable!("map fields are messages")
        };
        let key = entry.map_entry_key_field();
        let value = entry.map_entry_value_field();
        let (key_attr, key_ty) = scalar(&key.kind()).unwrap_or_else(|| fail("map key type"));
        let (value_attr, value_ty) = match value.kind() {
            Kind::Message(m) => ("message".to_string(), message_path(package, &m, "")),
            Kind::Enum(e) => (format!("enumeration({})", e.name()), "i32".to_string()),
            kind => scalar(&kind).unwrap_or_else(|| fail("map value type")),
        };
        return (
            format!("btree_map = \"{key_attr}, {value_attr}\""),
            format!("::std::collections::BTreeMap<{key_ty}, {value_ty}>"),
        );
    }
    let (attr, ty) = scalar_or_message(package, field, "");
    if field.cardinality() == Cardinality::Repeated {
        (
            format!("{attr}, repeated"),
            format!("::std::vec::Vec<{ty}>"),
        )
    } else if field.supports_presence() {
        (
            format!("{attr}, optional"),
            format!("::core::option::Option<{ty}>"),
        )
    } else {
        (attr, ty)
    }
}

fn scalar_or_message(package: &str, field: &FieldDescriptor, prefix: &str) -> (String, String) {
    match field.kind() {
        Kind::Message(m) => ("message".into(), message_path(package, &m, prefix)),
        Kind::Enum(e) => (
            format!("enumeration = \"{}{}\"", prefix, e.name()),
            "i32".into(),
        ),
        kind => {
            let (attr, ty) = scalar(&kind).unwrap_or_else(|| fail("field type"));
            if attr == "bytes" {
                ("bytes = \"vec\"".into(), ty)
            } else {
                (attr, ty)
            }
        }
    }
}

fn scalar(kind: &Kind) -> Option<(String, String)> {
    let (attr, ty) = match kind {
        Kind::Double => ("double", "f64"),
        Kind::Float => ("float", "f32"),
        Kind::Int32 => ("int32", "i32"),
        Kind::Int64 => ("int64", "i64"),
        Kind::Uint32 => ("uint32", "u32"),
        Kind::Uint64 => ("uint64", "u64"),
        Kind::Sint32 => ("sint32", "i32"),
        Kind::Sint64 => ("sint64", "i64"),
        Kind::Fixed32 => ("fixed32", "u32"),
        Kind::Fixed64 => ("fixed64", "u64"),
        Kind::Sfixed32 => ("sfixed32", "i32"),
        Kind::Sfixed64 => ("sfixed64", "i64"),
        Kind::Bool => ("bool", "bool"),
        Kind::String => ("string", "::std::string::String"),
        Kind::Bytes => ("bytes", "::std::vec::Vec<u8>"),
        Kind::Message(_) | Kind::Enum(_) => return None,
    };
    Some((attr.into(), ty.into()))
}

fn message_path(package: &str, message: &MessageDescriptor, prefix: &str) -> String {
    if message.package_name() == package {
        return format!("{prefix}{}", message.name());
    }
    match message.full_name() {
        "google.protobuf.Timestamp" => "::prost_types::Timestamp".into(),
        "google.protobuf.Duration" => "::prost_types::Duration".into(),
        "google.protobuf.Struct" => "::prost_types::Struct".into(),
        "google.protobuf.Value" => "::prost_types::Value".into(),
        "google.protobuf.Empty" => "()".into(),
        other => fail(&format!("message type {other} outside {package}")),
    }
}

fn render_enum(out: &mut String, e: &EnumDescriptor) {
    let name = e.name();
    out.push_str(
        "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, ::prost::Enumeration)]\n#[repr(i32)]\n",
    );
    let _ = writeln!(out, "pub enum {name} {{");
    let prefix = camel(&screaming_to_snake(name));
    let variants: Vec<(String, String, i32)> = e
        .values()
        .map(|v| {
            let full = camel(&v.name().to_lowercase());
            let stripped = full
                .strip_prefix(&prefix)
                .filter(|rest| rest.chars().next().is_some_and(|c| c.is_ascii_uppercase()));
            (
                stripped.unwrap_or(&full).to_string(),
                v.name().to_string(),
                v.number(),
            )
        })
        .collect();
    for (variant, _, number) in &variants {
        let _ = writeln!(out, "    {variant} = {number},");
    }
    out.push_str("}\n");
    let _ = writeln!(
        out,
        "impl {name} {{\n    pub fn as_str_name(&self) -> &'static str {{\n        match self {{"
    );
    for (variant, proto, _) in &variants {
        let _ = writeln!(out, "            Self::{variant} => \"{proto}\",");
    }
    out.push_str("        }\n    }\n    pub fn from_str_name(value: &str) -> ::core::option::Option<Self> {\n        match value {\n");
    for (variant, proto, _) in &variants {
        let _ = writeln!(out, "            \"{proto}\" => Some(Self::{variant}),");
    }
    out.push_str("            _ => None,\n        }\n    }\n}\n");
}

/// LeaseState -> lease_state, matching the SCREAMING_SNAKE value prefix.
fn screaming_to_snake(camel_name: &str) -> String {
    let mut out = String::new();
    for (i, c) in camel_name.chars().enumerate() {
        if c.is_ascii_uppercase() && i > 0 {
            out.push('_');
        }
        out.push(c.to_ascii_lowercase());
    }
    out
}

fn snake(name: &str) -> String {
    screaming_to_snake(name)
}

fn camel(snake_name: &str) -> String {
    snake_name
        .split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            let first = chars.next().map(|c| c.to_ascii_uppercase());
            first.into_iter().chain(chars).collect::<String>()
        })
        .collect()
}

fn ident(name: &str) -> String {
    const KEYWORDS: &[&str] = &[
        "as", "async", "await", "box", "break", "const", "continue", "crate", "dyn", "else",
        "enum", "extern", "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod",
        "move", "mut", "pub", "ref", "return", "self", "static", "struct", "super", "trait",
        "true", "type", "unsafe", "use", "where", "while", "yield", "gen",
    ];
    if KEYWORDS.contains(&name) {
        format!("r#{name}")
    } else {
        name.into()
    }
}
