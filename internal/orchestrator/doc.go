// Package orchestrator sets up Poe, the orchestrator: an ordinary sleeve whose
// workspace holds generated project context files and a scoped token, and whose
// only tool is the protectorate CLI. The harness itself is left untouched.
package orchestrator

import (
	"fmt"
	"path"
	"sort"
	"strings"
	"time"

	"github.com/hotschmoe/protectorate/internal/auth"
)

// Command is one runnable CLI command, extracted from the cobra tree.
type Command struct {
	Path  string // "sleeve spawn"
	Use   string // "spawn <name> --workspace <dir> ..."
	Short string
	Flags []Flag
}

type Flag struct {
	Name    string
	Type    string
	Default string
	Usage   string
}

// Tool is one hub RPC as the MCP bridge lists it.
type Tool struct {
	Name        string
	Description string
	ReadOnly    bool
	Destructive bool
}

// Workflow is the ordered list of commands the role text points the
// orchestrator at; a test checks each exists in the CLI.
var Workflow = []struct{ Command, Purpose string }{
	{"quota suggest --for medium", "rank harnesses by usable spare capacity before reset"},
	{"quota", "raw usage windows, resets and freshness per subscription"},
	{"backlog ls", "the owner's notes (pinned first), to discuss or act on"},
	{"backlog show", "read one note in full"},
	{"sleeve ls", "running sleeves with CPU, memory and workspace"},
	{"sleeve spawn", "start a harness in an isolated workspace"},
	{"sleeve resleeve", "move a sleeve to another harness with a hub-written handoff (no confirmation needed)"},
	{"session capture", "read what a sleeve's pane shows right now"},
	{"backlog edit", "update a note, e.g. --append or --body, when the owner asks"},
	{"events", "stream hub events as they happen"},
}

// DocInput is everything AGENTS.md is generated from.
type DocInput struct {
	Generated time.Time
	Harness   string
	Hub       string
	Token     TokenSummary
	Commands  []Command
	Tools     []Tool
}

type TokenSummary struct {
	ID      string
	Name    string
	Scopes  []string
	Expires string // formatted, or "never"
}

const description = 160

// RenderAgents returns AGENTS.md. Output depends only on din, with commands,
// flags and tools sorted, so regenerating with unchanged inputs is byte-stable.
func RenderAgents(din DocInput) []byte {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }

	w("# Poe, the Protectorate orchestrator\n\n")
	w("Generated by `protectorate orchestrator spawn` at %s. Regenerated on every spawn; edits here are lost.\n", din.Generated.UTC().Format(time.RFC3339))
	w("Put your own standing notes in `NOTES.md` in this directory and read it at the start of a session.\n\n")

	w("## Role\n\n")
	w("You are running as the %s harness in a sleeve named `poe`, an isolated sandbox on the hub machine.\n", din.Harness)
	w("You oversee the other sleeves (harness sessions in their own workspaces), read subscription quota, pick which harness should do which work, and read and edit the owner's notes (`protectorate backlog ...`).\n\n")
	w("- Act only through the `protectorate` CLI against the hub at `%s`. Your token is already configured (`PROTECTORATE_TOKEN_FILE`); never print, copy or move it.\n", din.Hub)
	w("- Use `--json` whenever you parse output.\n")
	w("- Never run a destructive action (killing a sleeve or session, removing a node, anything irreversible) without the user's explicit approval in this conversation, even if your token would allow it. Ask first and say what it will affect.\n")
	w("- Do not try to widen your own permissions or work around a `permission_denied`. Report it to the user instead.\n")
	w("- Start work only with `protectorate sleeve spawn`, which runs in a sandbox. Raw sessions run outside any sandbox and are not granted to you.\n")
	w("- When a chat sleeve's subscription runs low, move it with `protectorate sleeve resleeve <name> --to auto`; no confirmation is needed. The hub writes the handoff and tells the new harness to read it. Terminal and shell sleeves cannot be resleeved.\n")
	w("- Unknown or stale quota is not spare capacity. Prefer fresh data; run `protectorate quota suggest --refresh` when in doubt.\n")
	w("- Work donated to public repositories lands in a review inbox (a branch on a fork plus a summary). Nothing public goes out without the user's approval.\n")
	w("- This sandbox holds no SSH keys or harness credentials. `hosts.md` lists the user's machines for reference only.\n\n")

	w("## How to decide\n\n")
	for _, s := range Workflow {
		w("- `protectorate %s`: %s\n", s.Command, s.Purpose)
	}
	w("\nTypical loop: read the notes for what the owner wants done, ask `quota suggest` which harness has capacity that would otherwise expire, spawn a sleeve on it for one piece of work, watch the sleeve, then report back and update the note.\n\n")

	w("## Your token\n\n")
	w("- id `%s`, name `%s`, expires %s\n", din.Token.ID, din.Token.Name, din.Token.Expires)
	w("- scopes: `%s`\n\n", strings.Join(din.Token.Scopes, "`, `"))
	w("A call outside these scopes fails with `permission_denied`, and the hub's audit log records the attempt.\n\n")

	w("## Hub tools\n\n")
	w("Each tool is also a CLI command or `protectorate api call <Service>/<Method> '<json>'`. Tool names are the scope names.\n\n")
	w("| Tool | Access | Granted | Description |\n|------|--------|---------|-------------|\n")
	tools := append([]Tool(nil), din.Tools...)
	sort.Slice(tools, func(i, j int) bool { return tools[i].Name < tools[j].Name })
	for _, t := range tools {
		access := "mutating"
		switch {
		case t.ReadOnly:
			access = "read-only"
		case t.Destructive:
			access = "destructive"
		}
		granted := "no"
		if auth.Grants(din.Token.Scopes, t.Name) {
			granted = "yes"
		}
		w("| `%s` | %s | %s | %s |\n", t.Name, access, granted, cell(firstSentence(t.Description, description)))
	}

	w("\n## CLI reference\n\n")
	w("Global flags: `--hub URL` (env `PROTECTORATE_HUB`), `--token-file FILE` (env `PROTECTORATE_TOKEN_FILE`), `--json`.\n\n")
	cmds := append([]Command(nil), din.Commands...)
	sort.Slice(cmds, func(i, j int) bool { return cmds[i].Path < cmds[j].Path })
	for _, c := range cmds {
		w("### protectorate %s\n\n", c.Use)
		if c.Short != "" {
			w("%s\n\n", c.Short)
		}
		flags := append([]Flag(nil), c.Flags...)
		sort.Slice(flags, func(i, j int) bool { return flags[i].Name < flags[j].Name })
		for _, f := range flags {
			def := ""
			if f.Default != "" {
				def = fmt.Sprintf(" (default %s)", f.Default)
			}
			w("- `--%s %s`: %s%s\n", f.Name, f.Type, f.Usage, def)
		}
		if len(flags) > 0 {
			w("\n")
		}
	}
	return []byte(b.String())
}

func cell(s string) string {
	return strings.NewReplacer("|", "/", "\n", " ").Replace(s)
}

// firstSentence cuts s at the first sentence end, or at max runes.
func firstSentence(s string, limit int) string {
	s = strings.Join(strings.Fields(s), " ")
	if i := strings.Index(s, ". "); i >= 0 {
		s = s[:i+1]
	}
	if r := []rune(s); len(r) > limit {
		s = string(r[:limit-3]) + "..."
	}
	return s
}

// DefaultGrants are the tool globs Poe is given; destructive tools matched by
// them are dropped, so a new kill-style RPC is never granted by accident.
// message_* lets Poe answer the escalations the mailbox sends it.
// session_* is deliberately absent: session creation starts host processes
// outside any sandbox. Poe starts work only through sandboxed sleeves.
var DefaultGrants = []string{"backlog_*", "lease_*", "message_*", "sleeve_spawn_sleeve", "sleeve_resleeve_sleeve"}

// DefaultScopes is read, events and the explicit names of the mutating,
// non-destructive tools matched by DefaultGrants. Naming tools instead of
// keeping globs makes the grant visible and stable.
func DefaultScopes(tools []Tool) []string {
	scopes := []string{auth.ScopeRead, auth.ScopeEvents}
	for _, t := range tools {
		if t.ReadOnly || t.Destructive {
			continue
		}
		for _, g := range DefaultGrants {
			if ok, _ := path.Match(g, t.Name); ok {
				scopes = append(scopes, t.Name)
				break
			}
		}
	}
	sort.Strings(scopes)
	return scopes
}

// MergeScopes appends extra to base, dropping duplicates and keeping order.
func MergeScopes(base, extra []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, s := range append(append([]string(nil), base...), extra...) {
		if s != "" && !seen[s] {
			seen[s] = true
			out = append(out, s)
		}
	}
	return out
}
